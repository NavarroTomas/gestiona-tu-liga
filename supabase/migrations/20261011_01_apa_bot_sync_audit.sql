create table if not exists public.apa_bot_sync_runs (
  id bigint generated by default as identity primary key,
  guild_id text not null,
  season_id integer not null,
  season text not null,
  payload_hash text not null,
  clubs_count integer not null default 0,
  players_count integer not null default 0,
  transfers_count integer not null default 0,
  releases_count integer not null default 0,
  status text not null check (status in ('received', 'applied', 'failed')),
  error_message text,
  created_at timestamptz not null default now()
);

create unique index if not exists apa_bot_sync_runs_payload_hash_idx
  on public.apa_bot_sync_runs (payload_hash);

alter table public.apa_bot_sync_runs enable row level security;

revoke all on public.apa_bot_sync_runs from anon, authenticated;
grant all on public.apa_bot_sync_runs to service_role;
